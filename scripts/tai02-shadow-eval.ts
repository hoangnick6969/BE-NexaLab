// TAI2-T5 shadow evaluation on a SYNTHETIC set (team-lead decision 2026-11-09: real shadow data is not collected).
// Generates >= 100 synthetic responses across 3 written tasks with a fixed seed, runs each through the real
// ASSESS_SUBMISSION pipeline (redaction + fail-closed guard, injection@1, the provider request builder, the provider
// port, strict parse + KX-01, VA-01..05) with the deterministic FakeAiProvider, compares the suggestions with the
// synthetic teacher grades and computes the release metrics. No database is read or written; no network call is made.
//
//   npm run eval:tai02-shadow                       (report on stdout)
//   npm run eval:tai02-shadow -- --out <report.md>  (also writes the markdown report)
//   npm run eval:tai02-shadow -- --json
import { writeFileSync } from "node:fs";
import { parseAiConfig } from "../src/modules/ai/application/ai-config";
import { ASSESS_SUBMISSION_PROMPT_VERSION } from "../src/modules/ai/application/assess-submission-prompt";
import { renderShadowReport } from "../src/modules/ai/application/assessment-evaluation";
import { generateSyntheticSet, runSyntheticShadow, SYNTHETIC_SEED, SYNTHETIC_TASKS } from "../src/modules/ai/application/assessment-synthetic-shadow";
import { FakeAiProvider } from "../src/modules/ai/infrastructure/fake-provider";

function arg(name: string): string | null {
  const index = process.argv.indexOf(name);
  return index >= 0 ? (process.argv[index + 1] ?? null) : null;
}

async function main() {
  // Same config path as the API (fake is refused when APP_ENV or NODE_ENV is production).
  const config = parseAiConfig({ AI_PROVIDER: "fake" } as NodeJS.ProcessEnv);
  const provider = new FakeAiProvider();
  const set = generateSyntheticSet();
  const run = await runSyntheticShadow(provider, { promptVersion: ASSESS_SUBMISSION_PROMPT_VERSION, model: config.model! }, set);
  if (provider.calls.length !== run.providerCalls) throw new Error(`expected ${run.providerCalls} provider calls, got ${provider.calls.length}`);

  const markdown = renderShadowReport(run.report, {
    date: new Date().toISOString().slice(0, 10),
    source: "SYNTHETIC",
    notes: [
      `Generated by \`npm run eval:tai02-shadow\` (seed ${SYNTHETIC_SEED}); ${run.generated} synthetic responses across ${SYNTHETIC_TASKS.length} written tasks (${SYNTHETIC_TASKS.map((t) => t.topic).join("; ")}); ${run.ineligible} were ineligible for the provider; ${run.providerCalls} provider calls (responses matching injection@1 were suppressed without a call).`,
      "Synthetic teacher grades: the latent anchor level of each generated response, with a random half-point disagreement on about 12 % of criteria and full credit for paraphrased ideas on about 8 % of answered criteria (the fake adapter only recognises the exact anchor phrases, so paraphrases are where it disagrees).",
      "Each synthetic task totals 10 points. An earlier synthetic run with 3–4-point rubrics (same seed and noise rates) failed the within ±1 check at 74.4 %, because a single half-point disagreement on a 3-point rubric is 1.67 points on the 10-point scale; small rubrics make this gate strict, which matters for real tasks too.",
      "AI side: the deterministic FakeAiProvider (team-lead decision 2026-11-09, gate G-2 for dev/test under policy g2-pii-scrub@1). No live model was called, no data left the machine.",
      "Real shadow data (the supervising lecturer grading >= 100 real submissions blind) has NOT been collected. This report proves the evaluation harness and the pipeline only; it is not evidence of real model quality and must not be used to enable assist mode in production (the boot check refuses a SYNTHETIC pass in production).",
      "The admin route GET /admin/ai-assessment/evaluation computes the same metrics from stored shadow suggestions and MANUAL teacher grades.",
    ],
  });
  const out = arg("--out");
  if (out) writeFileSync(out, markdown, "utf8");
  if (process.argv.includes("--json")) console.log(JSON.stringify(run.report, null, 2));
  else console.log(markdown);
  console.log(`${run.report.pass ? "PASS" : "FAIL"} (SYNTHETIC): ${run.report.checks.filter((c) => c.pass).length}/${run.report.checks.length} checks${out ? `; report written to ${out}` : ""}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
